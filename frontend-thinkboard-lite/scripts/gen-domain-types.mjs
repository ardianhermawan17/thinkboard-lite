// Generates src/shared/types/domain/<table>.ts from `supabase gen types typescript` (task 003 g1, ffa §5).
// The output is GENERATED: never hand-edit it, rerun `npm run gen:types`. common.ts is the one hand-written file.
// An id, a foreign key and a *_at column are branded from ./common, never a bare string (I9).
import { spawnSync } from "node:child_process"
import { existsSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const DOMAIN = join(ROOT, "src/shared/types/domain")

export const fileName = (table) => `${table.replaceAll("_", "-")}.ts`
// highlight_notes -> HighlightNote, profile_identities -> ProfileIdentity
export const typeName = (table) =>
  table.replace(/ies$/, "y").replace(/s$/, "").split("_").map((w) => w[0].toUpperCase() + w.slice(1)).join("")

// The CLI prints a regular, indented shape; this reads only what the domain files need and fails loudly on the rest.
export function parse(text) {
  const enums = {}
  const tables = {}
  let mode = null
  let table = null
  let section = null
  let cols = []
  let enumName = null
  for (const line of text.replace(/\r\n/g, "\n").split("\n")) {
    let m
    if (/^export const /.test(line)) break // the trailing `Constants` block repeats Enums as arrays: not ours
    if (/^ {4}Tables: \{$/.test(line)) mode = "tables"
    else if (/^ {4}Enums: \{$/.test(line)) mode = "enums"
    else if (/^ {4}(Views|Functions|CompositeTypes): \{$/.test(line)) mode = null
    else if (mode === "tables") {
      if ((m = line.match(/^ {6}(\w+): \{$/))) tables[(table = m[1])] = { row: [], fks: {} }
      else if (/^ {8}Row: \{$/.test(line)) section = "row"
      else if (/^ {8}Relationships: \[/.test(line)) section = "rel"
      else if (/^ {8}(Insert|Update): \{$/.test(line)) section = null
      else if (section === "row" && (m = line.match(/^ {10}(\w+): (.+)$/))) tables[table].row.push({ col: m[1], type: m[2] })
      else if (section === "rel" && (m = line.match(/^ {12}columns: \[(.*)\]$/))) cols = [...m[1].matchAll(/"(\w+)"/g)].map((x) => x[1])
      else if (section === "rel" && (m = line.match(/^ {12}referencedRelation: "(\w+)"$/))) for (const c of cols) tables[table].fks[c] = m[1]
    } else if (mode === "enums") {
      if ((m = line.match(/^ {6}(\w+):(?: (.+))?$/))) {
        enumName = m[1]
        enums[enumName] = m[2] ?? ""
      } else if (enumName && (m = line.match(/^ {8}\| (.+)$/))) enums[enumName] += (enums[enumName] ? " | " : "") + m[1]
    }
  }
  if (!Object.keys(tables).length) throw new Error("no tables found: the supabase gen types output has an unexpected shape")
  return { enums, tables }
}

function brand(table, { col, type }, fks, enums) {
  const t = type.replace(/Database\["public"\]\["Enums"\]\["(\w+)"\]/g, (_, e) => {
    if (!enums[e]) throw new Error(`enum "${e}" (${table}.${col}) is not in the generated Enums block`)
    return enums[e]
  })
  if (!/^string(?= \||$)/.test(t)) return t // only plain string columns can be ids or timestamps
  const b = fks[col] ? `UUID<"${fks[col]}">` : col === "id" ? `UUID<"${table}">` : /_id$/.test(col) ? "UUID" : /_at$/.test(col) ? "ISODateString" : null
  return b ? t.replace(/^string/, b) : t
}

// -> Map<file name, contents> for the requested tables only
export function generate(text, tableNames) {
  const { enums, tables } = parse(text)
  const files = new Map()
  for (const name of tableNames) {
    if (!tables[name]) throw new Error(`table "${name}" is not found in the generated types`)
    const rows = tables[name].row.map((c) => ({ col: c.col, type: brand(name, c, tables[name].fks, enums) }))
    const used = ["ISODateString", "Json", "UUID"].filter((n) => rows.some((r) => new RegExp(`\\b${n}\\b`).test(r.type)))
    files.set(
      fileName(name),
      `// GENERATED by scripts/gen-domain-types.mjs from \`supabase gen types typescript\`. Do not edit: run \`npm run gen:types\`.\n` +
        (used.length ? `import type { ${used.join(", ")} } from "./common"\n` : "") +
        `\nexport type ${typeName(name)} = {\n${rows.map((r) => `  ${r.col}: ${r.type}`).join("\n")}\n}\n`
    )
  }
  return files
}

function fromCli() {
  const r = spawnSync("npx supabase gen types typescript --local --schema public", {
    cwd: join(ROOT, "..", "database-thinkboard-lite"),
    encoding: "utf8",
    shell: true,
    maxBuffer: 16 * 1024 * 1024,
  })
  if (r.status !== 0) throw new Error(`supabase gen types failed (is the local stack up? npm run start in database-thinkboard-lite/):\n${r.stderr}`)
  return r.stdout
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (!existsSync(join(DOMAIN, "common.ts"))) throw new Error(`${DOMAIN}/common.ts is missing: it is the hand-written brand file`)
  const blueprint = JSON.parse(readFileSync(join(ROOT, "architecture.blueprint.json"), "utf8"))
  // parked tables are not live in Lite: no domain type until they are
  const names = blueprint.domainTables.filter((t) => t.lite !== "parked").map((t) => t.name)
  const files = generate(fromCli(), names)
  for (const [file, contents] of files) writeFileSync(join(DOMAIN, file), contents)
  // a table that was dropped or parked leaves a stale file behind: remove generated files no longer in the list
  // (only files with our header, so the hand-written common.ts is never touched)
  const stale = readdirSync(DOMAIN).filter((f) => !files.has(f) && readFileSync(join(DOMAIN, f), "utf8").startsWith("// GENERATED"))
  for (const f of stale) unlinkSync(join(DOMAIN, f))
  console.log(`wrote ${files.size} domain type files to src/shared/types/domain/${stale.length ? `, removed ${stale.length} stale` : ""}`)
}
